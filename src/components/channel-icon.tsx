const LUCIDE = { sms: MessageSquareText, letter: Mailbox, call: PhoneCall, voicemail: Voicemail } as const;

/** A step's channel, as an icon. Anything unknown reads as an email, the channel most steps are. */
export function ChannelIcon({ channel, className = "size-4" }: { channel: Channel; className?: string }) {
  const classes = `shrink-0 ${className}`;
  const mark = BRAND_MARKS[channel];
  if (mark) {
    return (
      <svg viewBox="0 0 24 24" aria-hidden className={`fill-current ${classes}`}>
        <path d={mark} />
      </svg>
    );
  }
  if (channel === "instagram") {
    return (
      <svg viewBox="0 0 24 24" aria-hidden className={classes} fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round">
        <rect x="2.5" y="2.5" width="19" height="19" rx="5.5" />
        <circle cx="12" cy="12" r="4.25" />
        <circle cx="17.6" cy="6.4" r="0.6" fill="currentColor" stroke="none" />
      </svg>
    );
  }
  const Icon = LUCIDE[channel as keyof typeof LUCIDE] ?? Mail;
  return <Icon aria-hidden className={classes} />;
}

/** The icon on its own small tile, leading a row. */
export function ChannelTile({ channel }: { channel: Channel }) {
  return (
    <span className="grid size-9 shrink-0 place-items-center rounded-lg border bg-surface text-ice">
      <ChannelIcon channel={channel} />
    </span>
  );
}
